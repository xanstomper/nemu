class UiGeometryBuilder {
public:
    static void AddQuad(std::vector<core::gpu::RasterVertex>& out,
                        float px, float py, float pw, float ph,
                        UiColor col, float sw = 1280.0f, float sh = 720.0f) {
        const float x0 = (px / (sw * 0.5f)) - 1.0f;
        const float x1 = ((px + pw) / (sw * 0.5f)) - 1.0f;
        const float y0 = 1.0f - (py / (sh * 0.5f));
        const float y1 = 1.0f - ((py + ph) / (sh * 0.5f));

        // Triangle 1
        out.push_back({.x = x0, .y = y0, .r = col.r, .g = col.g, .b = col.b, .a = col.a});
        out.push_back({.x = x1, .y = y0, .r = col.r, .g = col.g, .b = col.b, .a = col.a});
        out.push_back({.x = x0, .y = y1, .r = col.r, .g = col.g, .b = col.b, .a = col.a});

        // Triangle 2
        out.push_back({.x = x1, .y = y0, .r = col.r, .g = col.g, .b = col.b, .a = col.a});
        out.push_back({.x = x1, .y = y1, .r = col.r, .g = col.g, .b = col.b, .a = col.a});
        out.push_back({.x = x0, .y = y1, .r = col.r, .g = col.g, .b = col.b, .a = col.a});
    }

    static void AddRectOutline(std::vector<core::gpu::RasterVertex>& out,
                               float px, float py, float pw, float ph, float thickness,
                               UiColor col, float sw = 1280.0f, float sh = 720.0f) {
        // Top
        AddQuad(out, px, py, pw, thickness, col, sw, sh);
        // Bottom
        AddQuad(out, px, py + ph - thickness, pw, thickness, col, sw, sh);
        // Left
        AddQuad(out, px, py + thickness, thickness, ph - (thickness * 2.0f), col, sw, sh);
        // Right
        AddQuad(out, px + pw - thickness, py + thickness, thickness, ph - (thickness * 2.0f), col, sw, sh);
    }

    /// Filled circle centered at (cx, cy), built from 1px-tall horizontal spans
    /// (midpoint circle fill). Cheap and smooth at UI scale.
    static void AddDisc(std::vector<core::gpu::RasterVertex>& out,
                        float cx, float cy, float r, UiColor col,
                        float sw = 1280.0f, float sh = 720.0f) {
        const int rows = static_cast<int>(r) + 1;
        for (int dy = -rows; dy <= rows; ++dy) {
            const float y = static_cast<float>(dy);
            if (y < -r || y > r) continue;
            const float half = std::sqrt(r * r - y * y);
            AddQuad(out, cx - half, cy + y, half * 2.0f, 1.0f, col, sw, sh);
        }
    }

    /// Circle outline (ring) of the given thickness centered at (cx, cy).
    static void AddRing(std::vector<core::gpu::RasterVertex>& out,
                        float cx, float cy, float r, float thickness, UiColor col,
                        float sw = 1280.0f, float sh = 720.0f) {
        const float r_in = r - thickness;
        const int rows = static_cast<int>(r) + 1;
        for (int dy = -rows; dy <= rows; ++dy) {
            const float y = static_cast<float>(dy);
            if (y < -r || y > r) continue;
            const float ho = std::sqrt(r * r - y * y);
            float hi = 0.0f;
            if (y >= -r_in && y <= r_in && r_in > 0.0f) {
                hi = std::sqrt(r_in * r_in - y * y);
            }
            // Left span
            AddQuad(out, cx - ho, cy + y, ho - hi, 1.0f, col, sw, sh);
            // Right span
            AddQuad(out, cx + hi, cy + y, ho - hi, 1.0f, col, sw, sh);
        }
    }

    static void AddText(std::vector<core::gpu::RasterVertex>& out,
                        std::string_view text, float px, float py, float scale,
                        UiColor col, float sw = 1280.0f, float sh = 720.0f) {
        float cur_x = px;
        const float char_step = 8.0f * scale;

        for (char ch : text) {
            if (ch == '\n') {
                py += 10.0f * scale;
                cur_x = px;
                continue;
            }
            if (ch < 32 || ch > 126) {
                ch = '?';
            }
            const uint32_t idx = static_cast<uint32_t>(ch - 32);
            const auto& glyph = kFont8x8[idx];

            for (int r = 0; r < 8; ++r) {
                const uint8_t row_byte = glyph[r];
                if (row_byte == 0) continue;

                int c = 0;
                while (c < 8) {
                    if (row_byte & (0x80 >> c)) {
                        int run_len = 1;
                        while (c + run_len < 8 && (row_byte & (0x80 >> (c + run_len)))) {
                            run_len++;
                        }
                        AddQuad(out, cur_x + static_cast<float>(c) * scale,
                                py + static_cast<float>(r) * scale,
                                static_cast<float>(run_len) * scale,
                                scale, col, sw, sh);
                        c += run_len;
                    } else {
                        c++;
                    }
                }
            }
            cur_x += char_step;
        }
    }
};

